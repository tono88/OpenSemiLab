import { readFile } from 'node:fs/promises'
import { expect, test, type Page } from '@playwright/test'
import { DEVICES, GUIDES } from '../../src/deviceLab/catalogue'

async function ready(page: Page) { await expect(page.getByTestId('lab-status')).toHaveText('CALCULADO') }
async function jsonExport(page: Page) {
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Exportar experimento JSON', exact: true }).click()
  return JSON.parse(await readFile((await (await download).path())!, 'utf8'))
}
test.beforeEach(async ({ page }) => {
  // Offline Design Studio uses its shipped templates. Device models must not
  // depend on a live API or any SMTP/production service.
  await page.route('**/api/**', route => route.fulfill({ status: 503, json: { detail: 'offline fixture' } }))
  await page.route('https://fonts.googleapis.com/**', route => route.abort())
  await page.goto('/tests/browser/device-lab.html')
  await page.getByRole('button', { name: 'Laboratorio de dispositivos', exact: true }).click()
  await ready(page)
})

