test('PN TCAD and mesh validation send their jobs directly to the client companion', async ({ page }) => {
  const jobs: { url: string; body: any }[] = [], serverSimulations: string[] = []
  page.on('request', request => {
    if (request.method() === 'POST' && /simulations|validation/.test(request.url()) && !request.url().startsWith('http://127.0.0.1:8787/')) serverSimulations.push(request.url())
  })
  // This fixture verifies routing/contracts, not the physics of the native
  // solver; the companion's integration suite runs real DEVSIM separately.
  const result = { experiment_name: 'local routing fixture', metrics: [{ label: 'Fixture voltage', value: .714, unit: 'V' }], series: [{ name: 'potential', x_label: 'Position', x_unit: 'µm', y_label: 'Potential', y_unit: 'V', x: [-1, 0, 1], y: [0, .357, .714] }], explanations: [], warnings: [], converged: true, provenance: { engine: 'devsim', engine_version: 'routing-fixture', model: 'fixture-only', input_sha256: 'abc123', authoritative: false, execution_host: 'local-companion' } }
  await page.route('http://127.0.0.1:8787/**', async route => {
    const request = route.request(), headers = { 'Access-Control-Allow-Origin': '*', 'Access-Control-Allow-Methods': 'GET,POST,OPTIONS', 'Access-Control-Allow-Headers': 'content-type' }
    if (request.method() === 'OPTIONS') { await route.fulfill({ status: 204, headers }); return }
    if (request.url().endsWith('/health')) { await route.fulfill({ headers, json: { ok: true } }); return }
    jobs.push({ url: request.url(), body: request.postDataJSON() })
    await route.fulfill({ headers, json: request.url().includes('/validation/') ? { passed: true, checks: [{ id: 'fixture', label: 'Routing fixture', value: 0, limit: 1, passed: true }], result, bundle: { bundle_sha256: 'fixture', result } } : result })
  })
  await page.getByRole('button', { name: 'Avanzado', exact: true }).click()
  expect(jobs).toEqual([])
  await page.getByRole('button', { name: 'Abrir DEVSIM local y validación de malla', exact: true }).click()
  const tcad = page.locator('.dl-tcad')
  await expect(tcad).toContainText('LOCAL CONECTADO')
  await tcad.getByRole('button', { name: 'Ejecutar TCAD local', exact: true }).click()
  await expect(tcad).toContainText('Fixture voltage')
  expect(jobs[0].url).toBe('http://127.0.0.1:8787/api/v1/simulations/pn-junction')
  expect(jobs[0].body.engine).toBe('devsim')
  expect(jobs[0].body.device.acceptor_cm3).toBe(1e16)
  await tcad.getByRole('button', { name: 'Validar 51 / 101 / 201', exact: true }).click()
  await expect(tcad).toContainText('Routing fixture')
  expect(jobs[1].url).toBe('http://127.0.0.1:8787/api/v1/validation/pn-junction')
  expect(jobs[1].body.mesh_points).toEqual([51, 101, 201])
  expect(serverSimulations).toEqual([])
  const svgDownload = page.waitForEvent('download')
  await tcad.getByRole('button', { name: 'Exportar SVG', exact: true }).click()
  const svg = await readFile((await (await svgDownload).path())!, 'utf8')
  expect(svg).toContain('local-companion')
  expect(svg).toContain('fixture-only')
  expect(svg).toContain('acceptor_cm3')
})
